-- 1. Purchase register and financial records


CREATE TABLE purchase_lines (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

-- Original inventory identification
original_s_no INTEGER,
description VARCHAR(250) NOT NULL,
quantity INTEGER NOT NULL CHECK (quantity > 0),

-- Purchase values
unit_price_pkr NUMERIC(16, 2),
extended_price_pkr NUMERIC(16, 2),
gst_rate_recorded NUMERIC(5, 2),
gst_amount_pkr NUMERIC(16, 2),
total_pkr NUMERIC(16, 2),
foreign_value_raw TEXT,

-- Historical depreciation values
purchase_date DATE,
valuation_date_recorded DATE,
days_recorded INTEGER,
tool_life_years_recorded INTEGER,
per_day_depreciation_recorded NUMERIC(18, 2),
depreciation_till_date_a_raw TEXT,
depreciation_till_date_b_raw TEXT,
nbv_recorded NUMERIC(16, 2),

-- Vendor and procurement
vendor VARCHAR(255),
local_or_imported VARCHAR(30),
part_no VARCHAR(120),
oes_po VARCHAR(120),
bill_no VARCHAR(120),
bill_date DATE,

-- Equipment and location
project_department VARCHAR(160),
lying_at VARCHAR(160),
series VARCHAR(120),
make VARCHAR(120),
condition_recorded VARCHAR(120),
issued_to_recorded VARCHAR(160),
transferred_to_recorded VARCHAR(160),

-- Preserve both original Type columns
type_1 VARCHAR(120),
type_2 VARCHAR(120),
purpose TEXT,
department VARCHAR(120),
remarks TEXT,

-- Original imported record
raw_row_json JSONB NOT NULL DEFAULT '{}'::jsonb,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Expand the existing individual tools table

ALTER TABLE tool_assets
ADD COLUMN purchase_line_id BIGINT,
ADD COLUMN serial_number VARCHAR(120),
ADD COLUMN part_number VARCHAR(120),
ADD COLUMN series VARCHAR(120),
ADD COLUMN make VARCHAR(120),
ADD COLUMN storage_location VARCHAR(160),
ADD COLUMN department VARCHAR(120),
ADD COLUMN tool_condition VARCHAR(40) NOT NULL DEFAULT 'UNASSESSED',
ADD COLUMN is_restricted BOOLEAN NOT NULL DEFAULT FALSE,
ADD COLUMN created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
ADD COLUMN updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW();

-- 3. Create the relationship

ALTER TABLE tool_assets
ADD CONSTRAINT fk_tool_purchase_line FOREIGN KEY (purchase_line_id) REFERENCES purchase_lines (id);

-- 4. Add indexes for common searches

CREATE INDEX idx_tool_purchase_line ON tool_assets (purchase_line_id);

CREATE INDEX idx_tool_status ON tool_assets (status);

CREATE INDEX idx_tool_department ON tool_assets (department);